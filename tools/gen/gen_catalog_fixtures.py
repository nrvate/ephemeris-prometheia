"""Generate tests/catalog_fixtures.inc from the Swiss Ephemeris swetest CLI.

Output-only oracle (docs/DESIGN.md, cleanroom policy): swetest runs as a
black box, planets on the same JPL DE440 binary the engine loads
(-ejpl<file>), the asteroid from SWE's own short asteroid file
(seas_18.se1, 1800-2399) via -xs<number>. The residuals therefore measure
the overlay's integration, seeding and frame conventions against an
independently computed asteroid ephemeris.

Usage:
  tools/gen/gen_catalog_fixtures.py [--swetest PATH] [--swe-ephe DIR]
      [--de-file FILE] [--gate ARCSEC] > tests/catalog_fixtures.inc
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

# TT Julian days: J2000 (26 yr before the catalog epoch), the catalog
# epoch itself, 2026-09, and roughly +/- 11 years around it.
EPOCHS = [2451545.0, 2461200.5, 2461300.25, 2465295.5, 2457105.5]

# (spkid in tests/data/sample-100.epm, MPC number swetest addresses).
BODIES = [(20000001, 1)]  # Ceres


def make_ephe_dir(de_file, swe_ephe):
    """swetest resolves the JPL file by basename inside -edir, so the DE
    binary and SWE's asteroid file must share one directory: a temp dir
    of symlinks."""
    d = tempfile.mkdtemp(prefix="swe-fixtures-")
    os.symlink(os.path.abspath(de_file), os.path.join(d, os.path.basename(de_file)))
    for extra in ("seas_18.se1",):
        src = os.path.join(swe_ephe, extra)
        if os.path.exists(src):
            os.symlink(src, os.path.join(d, extra))
    return d


def sexagesimal(s):
    s = s.strip()
    neg = s.startswith("-")
    m = re.match(r"-?(\d+)[°h]\s*(\d+)'\s*([\d.]+)", s)
    if not m:
        sys.exit("cannot parse swetest column: %r" % s)
    v = int(m.group(1)) + int(m.group(2)) / 60.0 + float(m.group(3)) / 3600.0
    return -v if neg else v


def run(args, ephe_dir, jd, mpc, flags, fmt):
    cmd = [
        args.swetest,
        "-ejpl" + os.path.abspath(args.de_file),
        "-edir" + ephe_dir,
        "-j%.10g" % jd,
        "-f" + fmt,
        "-ps",
        "-xs%d" % mpc,
        "-head",
        "-g|",
    ] + flags
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    if "error" in out.lower():
        sys.exit("swetest: " + out)
    rows = [line.split("|") for line in out.strip().splitlines()]
    if len(rows) != 1:
        sys.exit("expected one row, got: %r" % out)
    return rows[0]


def position(args, ephe_dir, jd, mpc, flags):
    r = run(args, ephe_dir, jd, mpc, flags, "PLBR")
    return sexagesimal(r[1]), sexagesimal(r[2]), float(r[3])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--swetest", default="/shares/swisseph/swetest")
    ap.add_argument("--swe-ephe", default="/shares/swisseph/ephe")
    ap.add_argument("--de-file", default="ephe/linux_p1550p2650.440")
    ap.add_argument("--gate", type=float, default=2.0,
                    help="worst apparent separation tolerated by the test, arcsec")
    args = ap.parse_args()

    apparent = []  # swetest default flags
    geometric = ["-true", "-noaberr", "-nodefl", "-j2000"]

    ephe_dir = make_ephe_dir(args.de_file, args.swe_ephe)
    print("// Generated by tools/gen/gen_catalog_fixtures.py from swetest on DE440")
    print("// plus SWE's seas_18.se1 asteroid file. Do not edit by hand. Degrees, AU.")
    print("constexpr double kCatalogGateArcsec = %.2f;" % args.gate)
    print("const CatalogFixture kCatalogFixtures[] = {")
    for jd in EPOCHS:
        for spkid, mpc in BODIES:
            lon, lat, dist = position(args, ephe_dir, jd, mpc, apparent)
            jlon, jlat, jdist = position(args, ephe_dir, jd, mpc, geometric)
            print("    {%.2f, %d, %.10f, %.10f, %.10f, %.10f, %.10f, %.10f},"
                  % (jd, spkid, lon, lat, dist, jlon, jlat, jdist))
    print("};")


if __name__ == "__main__":
    main()