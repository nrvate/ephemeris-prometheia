"""Generate src/lunar_saros.inc: the first member of each lunar saros series.

A lunar eclipse's saros series follows from its lunation number alone
(lunar_eclipse.cpp: L = 135 s + 208 mod 223). Its *member* number counts from
the series' first eclipse, which is a matter of convention that this table
records, read from NASA's Five Millennium Catalog of Lunar Eclipses
(Espenak and Meeus; credit: "Eclipse Predictions by Fred Espenak, NASA's
GSFC"; public domain). A series that was already running when the catalog
begins (-1999) has no known first member and is left out.

Input: the catalog file tools/fetch/eclipse_fetch.py fetches (sha256 pinned
there). Output rows are `{series, lunation of its first eclipse}`, the
lunation numbered as in lunar_eclipse.cpp.

Usage:
  gen_lunar_saros.py CATALOG.txt            # rewrite src/lunar_saros.inc
  gen_lunar_saros.py CATALOG.txt --check    # exit 1 if src/ is stale
"""
import argparse
import hashlib
import math
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "src", "lunar_saros.inc")
PIN = "d47586fc9c1c59338f234b3c6634c31744739887169f58d411ac766f3861fcf2"
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
ROW = re.compile(r"^(\d{5})\s+(-?\d+) (\w{3}) (\d+)\s+(\d\d):(\d\d):(\d\d)\s+(-?\d+)\s+(-?\d+)"
                 r"\s+(-?\d+)\s+(\w+[+-]?)\s")
K0, SYNODIC = 2451550.09766, 29.530588861


def jd(y, mo, d, sec):
    if mo <= 2:
        y, mo = y - 1, mo + 12
    b = 0
    if (y, mo, d) >= (1582, 10, 15) or y > 1582:
        a = y // 100
        b = 2 - a + a // 4
    return (math.floor(365.25 * (y + 4716)) + math.floor(30.6001 * (mo + 1)) + d + b
            - 1524.5 + sec / 86400.0)


def lunation(t):
    return round((t - K0) / SYNODIC - 0.5)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("catalog")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    raw = open(args.catalog, "rb").read()
    if hashlib.sha256(raw).hexdigest() != PIN:
        sys.exit("catalog sha256 differs from the pin in tools/fetch/eclipse_fetch.py")
    first = {}
    lmin = None
    for line in raw.decode("ascii").splitlines():
        m = ROW.match(line)
        if not m:
            continue
        y, mo, d = int(m[2]), MONTHS.index(m[3]) + 1, int(m[4])
        sec = int(m[5]) * 3600 + int(m[6]) * 60 + int(m[7])
        ell = lunation(jd(y, mo, d, sec))
        lmin = ell if lmin is None else lmin
        first.setdefault(int(m[10]), ell)
    rows = sorted((s, e) for s, e in first.items() if e >= lmin + 223)
    out = ("// SPDX-License-Identifier: GPL-2.0-or-later\n//\n"
           "// Generated by tools/gen/gen_lunar_saros.py from NASA's Five Millennium Catalog\n"
           "// of Lunar Eclipses (Eclipse Predictions by Fred Espenak, NASA's GSFC) -- do not\n"
           "// edit. {series, lunation of the series' first eclipse}; docs/ECLIPSES.md.\n"
           f"// {len(rows)} series.\n")
    out += "".join(f"{{{s}, {e}}},\n" for s, e in rows)
    if args.check:
        return 0 if open(OUT).read() == out else 1
    open(OUT, "w").write(out)
    print(f"{len(rows)} series -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
