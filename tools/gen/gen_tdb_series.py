"""Generate src/tdb_series.inc: the full Fairhead & Bretagnon (1990) TDB-TT
series, 787 terms in five powers of time, as ERFA carries it.

Source: ERFA (Essential Routines for Fundamental Astronomy) v2.0.1,
src/dtdb.c, BSD-3-Clause (Copyright (C) 2013-2023, NumFOCUS Foundation;
derived, with permission, from the IAU SOFA library). Only the coefficient
table is taken; the evaluation in src/time.cpp is our own. ERFA states the
series agrees with time ephemerides integrated on DE405 to +/- 3 ns over
1950-2050 (note 7 of dtdb.c). docs/TIME.md, "TDB", has why it replaced the
seven-term series.

This is a fixed publication, not a release-time refresh: one file, fetched
once, pinned by its sha256.

Usage:
  gen_tdb_series.py --fetch --raw-dir erfa-raw     # download + generate
  gen_tdb_series.py --raw-dir erfa-raw             # regenerate from cache
  gen_tdb_series.py --raw-dir erfa-raw --check     # exit 1 if src/ is stale
"""
import argparse
import hashlib
import os
import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/liberfa/erfa/v2.0.1/src/dtdb.c"
NAME = "dtdb.c"
SHA256 = "228bd7c7c1c88dda44c29a076f289c968f64d77a2dc389138b03ab5d1d442105"
USER_AGENT = "prometheia-gen/0.1.0 (Ephemeris Prometheia; one-time fetch of ERFA dtdb.c)"
# The first row of each power of t (Julian millennia), 0-based, from dtdb.c's
# evaluation loops (474 T^0 terms, 205 T^1, 85 T^2, 20 T^3, 3 T^4).
GROUPS = [0, 474, 679, 764, 784, 787]

# The engine's set: the terms that can move TDB-TT by at least 0.1 us
# anywhere in DE441's span, |t| <= 15.03 millennia (amplitude x |t|^power).
# Measured against all 787 every 2.4 days: 1.55 us worst over -13000..17000
# (at 13824), 0.94 us over 1550-2650. A JD held as a double quantizes an instant to 10-80 us there,
# so the rest cannot reach an answer; the public function keeps all 787.
ENGINE_FLOOR_S = 1e-7
ENGINE_T_MAX = 15.03

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "src", "tdb_series.inc")

ROW = re.compile(r"\{\s*([-+0-9.]+)e-6,\s*([-+0-9.]+),\s*([-+0-9.]+)\s*\}")


def fetch(raw_dir):
    os.makedirs(raw_dir, exist_ok=True)
    req = urllib.request.Request(URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as resp:
        body = resp.read()
    with open(os.path.join(raw_dir, NAME), "wb") as f:
        f.write(body)


def parse(raw_dir):
    with open(os.path.join(raw_dir, NAME), "rb") as f:
        blob = f.read()
    digest = hashlib.sha256(blob).hexdigest()
    if digest != SHA256:
        sys.exit(f"{NAME}: sha256 {digest}, expected {SHA256}")
    text = blob.decode("ascii")
    start = text.index("static const double fairhd[787][3]")
    end = text.index("};", start)
    rows = [(float(a), float(f), float(p)) for a, f, p in ROW.findall(text[start:end])]
    if len(rows) != GROUPS[-1]:
        sys.exit(f"expected {GROUPS[-1]} rows, found {len(rows)}")
    # The loops the grouping comes from, read from the file rather than trusted.
    for lo, hi in zip(GROUPS, GROUPS[1:]):
        if f"for (j = {hi - 1}; j >= {lo}; j--)" not in text:
            sys.exit(f"dtdb.c no longer sums rows {lo}..{hi - 1} as one power of t")
    if "wf = t * (t * (t * (t * w4 + w3) + w2) + w1) + w0;" not in text:
        sys.exit("dtdb.c combines the powers of t differently")
    return rows


def render(rows):
    out = [
        "// Generated by tools/gen/gen_tdb_series.py -- do not edit.",
        "// Fairhead & Bretagnon (1990) TDB-TT at the geocentre, full form: 787 terms",
        "// amplitude (microseconds), frequency (rad per Julian millennium), phase",
        "// (rad), grouped by the power of t (Julian millennia from J2000) that",
        "// multiplies each group's sum.",
        "// Source: ERFA v2.0.1 src/dtdb.c (BSD-3-Clause; Copyright (C) 2013-2023,",
        "// NumFOCUS Foundation; derived, with permission, from the IAU SOFA library).",
        f"//   {URL}",
        f"//     sha256 {SHA256}",
        "struct TdbTerm {",
        "    double amp_us, freq, phase;",
        "};",
        f"constexpr int kTdbGroupStart[] = {{{', '.join(str(g) for g in GROUPS)}}};",
        "constexpr TdbTerm kTdbTerms[] = {",
    ]
    for a, f, p in rows:
        out.append(f"    {{{a!r}, {f!r}, {p!r}}},")
    out.append("};")
    kept, starts = [], []
    for g in range(len(GROUPS) - 1):
        starts.append(len(kept))
        kept += [r for r in rows[GROUPS[g]:GROUPS[g + 1]]
                 if r[0] * 1e-6 * ENGINE_T_MAX ** g >= ENGINE_FLOOR_S]
    starts.append(len(kept))
    out += [
        f"// The engine's set ({len(kept)} terms): those that can move TDB-TT by",
        f"// {ENGINE_FLOOR_S:g} s or more at |t| <= {ENGINE_T_MAX} millennia (tools/gen/gen_tdb_series.py).",
        f"constexpr int kTdbEngineGroupStart[] = {{{', '.join(str(g) for g in starts)}}};",
        "constexpr TdbTerm kTdbEngineTerms[] = {",
    ]
    for a, f, p in kept:
        out.append(f"    {{{a!r}, {f!r}, {p!r}}},")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw-dir", required=True)
    ap.add_argument("--fetch", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.fetch:
        fetch(args.raw_dir)
    text = render(parse(args.raw_dir))
    if args.check:
        with open(OUT) as f:
            stale = f.read() != text
        print(f"{OUT}: {'stale' if stale else 'up to date'}")
        sys.exit(1 if stale else 0)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
