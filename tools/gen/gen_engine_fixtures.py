"""Generate tests/engine_fixtures.inc from the Swiss Ephemeris swetest CLI.

Output-only oracle (docs/DESIGN.md, Cleanroom policy): swetest is run as a
black box on JPL's own DE440 binary (-ejpl<file>), so the ephemeris is
identical on both sides and any difference is the apparent-place and frame
model. Positions are parsed from the 0.0001-arcsecond sexagesimal columns.

Usage:
  tools/gen/gen_engine_fixtures.py [--swetest PATH] [--ephe-dir DIR] > tests/engine_fixtures.inc
"""
import argparse
import os
import re
import subprocess
import sys

EPOCHS = [2378496.5, 2451545.0, 2461300.25, 2488069.5]  # TT: 1800, J2000, 2026-09, 2100
BODIES = [10, 301, 199, 299, 4, 5, 6, 7, 8, 9]            # swetest -p0123456789 order
SITE = (8.55, 47.37, 500.0)                               # lon, lat (deg), height (m)
SPEED_H = 0.01                                            # days, for differenced rates

# name -> (swetest flags, equatorial?)
MODES = {
    "Apparent": ([], False),
    "ApparentEquatorial": ([], True),
    "ApparentJ2000": (["-j2000"], False),
    "GeometricJ2000": (["-true", "-noaberr", "-nodefl", "-j2000"], False),
    "BarycentricJ2000": (["-bary", "-true", "-noaberr", "-nodefl", "-j2000"], False),
    "HeliocentricJ2000": (["-hel", "-true", "-noaberr", "-nodefl", "-j2000"], False),
    "Topocentric": (["-topo%g,%g,%g" % SITE], False),
}


def sexagesimal(s):
    s = s.strip()
    neg = s.startswith("-")
    m = re.match(r"-?(\d+)[°h]\s*(\d+)'\s*([\d.]+)", s)
    v = int(m.group(1)) + int(m.group(2)) / 60.0 + float(m.group(3)) / 3600.0
    return -v if neg else v


def run(args, jd, flags, fmt, bodies="0123456789"):
    cmd = [args.swetest, "-ejpl" + args.ephe_file, "-edir" + os.path.abspath(args.ephe_dir), "-j%.10g" % jd,
           "-f" + fmt, "-p" + bodies, "-head", "-g|"] + flags
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    if "error" in out.lower():
        sys.exit("swetest: " + out)
    return [line.split("|") for line in out.strip().splitlines()]


def positions(args, jd, flags, equatorial):
    rows = run(args, jd, flags, "PADR" if equatorial else "PLBR")
    names = [r[0].strip() for r in rows]
    vals = []
    for r in rows:
        a = sexagesimal(r[1]) * (15.0 if equatorial else 1.0)
        vals.append((a, sexagesimal(r[2]), float(r[3])))
    return names, vals


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--swetest", default="/shares/swisseph/swetest")
    ap.add_argument("--ephe-dir", default="ephe")
    ap.add_argument("--ephe-file", default="linux_p1550p2650.440")
    args = ap.parse_args()

    print("// Generated by tools/gen/gen_engine_fixtures.py from swetest on DE440.")
    print("// Do not edit by hand. Degrees (RA in degrees), AU.")
    print("struct Fixture { Mode mode; double jd_tt; int body; double a, b, r; };")
    print("const Fixture kFixtures[] = {")
    for mode, (flags, equ) in MODES.items():
        for jd in EPOCHS:
            names, vals = positions(args, jd, flags, equ)
            bodies = BODIES[1:] if "-hel" in flags else BODIES
            # -hel omits the Sun row and stops before Pluto in some builds.
            for body, (a, b, r) in zip(bodies, vals):
                print("    {Mode::%s, %.2f, %d, %.10f, %.10f, %.10f}," % (mode, jd, body, a, b, r))
    print("};")

    print("struct DeltaTFixture { double jd_tt, seconds; };")
    print("const DeltaTFixture kSweDeltaT[] = {")
    for jd in EPOCHS:
        dt = float(run(args, jd, [], "l", "q")[0][0].split()[-1])
        print("    {%.2f, %.7f}," % (jd, dt))
    print("};")

    print("// Apparent positions at jd -/+ %g day, for differenced rates." % SPEED_H)
    print("constexpr double kSpeedH = %g;" % SPEED_H)
    print("struct SpeedFixture { double jd_tt; int body; double a0, b0, r0, a1, b1, r1; };")
    print("const SpeedFixture kSpeedFixtures[] = {")
    for jd in EPOCHS[1:3]:
        _, lo = positions(args, jd - SPEED_H, [], False)
        _, hi = positions(args, jd + SPEED_H, [], False)
        for body, p, q in zip(BODIES, lo, hi):
            print("    {%.2f, %d, %.10f, %.10f, %.10f, %.10f, %.10f, %.10f}," %
                  ((jd, body) + p + q))
    print("};")


if __name__ == "__main__":
    main()
