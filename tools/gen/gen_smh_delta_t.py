"""Generate src/delta_t_smh_table.inc: the Stephenson-Morrison-Hohenkerk
Delta T spline, -720 to 2019, as cubic polynomial coefficients.

Source: Table S15 (v. 2020) of the electronic supplementary material of
  L. V. Morrison, F. R. Stephenson, C. Y. Hohenkerk & M. Zawilski (2021),
  "Addendum 2020 to 'Measurement of the Earth's rotation: 720 BC to AD 2015'",
  Proc. R. Soc. A 477: 20200776, https://doi.org/10.1098/rspa.2020.0776
published on figshare (item 13885863, CC BY 4.0) as rspa20200776_si_002.zip.
The analysis it updates: F. R. Stephenson, L. V. Morrison & C. Y. Hohenkerk
(2016), Proc. R. Soc. A 472: 20160404, https://doi.org/10.1098/rspa.2016.0404
(CC BY 4.0).

This is a fixed publication, not a release-time refresh: the table changes
only if the authors publish a new version. One file, fetched once.

Usage:
  gen_smh_delta_t.py --fetch --raw-dir smh-raw     # download + generate
  gen_smh_delta_t.py --raw-dir smh-raw             # regenerate from cache
  gen_smh_delta_t.py --raw-dir smh-raw --check     # exit 1 if src/ is stale
"""
import argparse
import hashlib
import io
import os
import sys
import urllib.request
import zipfile

URL = "https://ndownloader.figshare.com/files/26513569"
ZIP_NAME = "rspa20200776_si_002.zip"
ZIP_SHA256 = "1a649a163aa0e0e91a177a8b0dcd280aa0afadba715e9467cc030a0586d2cf37"
MEMBER = "Table-S15.2020.txt"
USER_AGENT = "prometheia-gen/0.1.0 (Ephemeris Prometheia; one-time fetch of a CC BY supplement)"

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "src", "delta_t_smh_table.inc")


def fetch(raw_dir):
    os.makedirs(raw_dir, exist_ok=True)
    req = urllib.request.Request(URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as resp:
        body = resp.read()
    with open(os.path.join(raw_dir, ZIP_NAME), "wb") as f:
        f.write(body)


def parse(raw_dir):
    with open(os.path.join(raw_dir, ZIP_NAME), "rb") as f:
        blob = f.read()
    digest = hashlib.sha256(blob).hexdigest()
    if digest != ZIP_SHA256:
        sys.exit(f"{ZIP_NAME}: sha256 {digest}, expected {ZIP_SHA256}")
    text = zipfile.ZipFile(io.BytesIO(blob)).read(MEMBER).decode("ascii")
    rows = []
    for line in text.splitlines():
        parts = line.split()
        if len(parts) == 7 and parts[0].isdigit():
            i = int(parts[0])
            k0, k1, a0, a1, a2, a3 = (float(p) for p in parts[1:])
            if i != len(rows) + 1:
                sys.exit(f"row {i} out of sequence")
            rows.append((k0, k1, a0, a1, a2, a3))
    if len(rows) != 58 or rows[0][0] != -720.0 or rows[-1][1] != 2019.0:
        sys.exit(f"unexpected table shape: {len(rows)} rows")
    for prev, cur in zip(rows, rows[1:]):
        if prev[1] != cur[0]:
            sys.exit(f"knots not contiguous at {cur[0]}")
        end = prev[2] + prev[3] + prev[4] + prev[5]
        if abs(end - cur[2]) > 0.01:  # the published 3-decimal rounding
            sys.exit(f"spline discontinuous at {cur[0]}: {end} vs {cur[2]}")
    return rows


def render(rows):
    out = [
        "// Generated by tools/gen/gen_smh_delta_t.py -- do not edit.",
        "// Delta T spline, -720.0 to 2019.0, v. 2020: Table S15 of the supplement to",
        "//   Morrison, Stephenson, Hohenkerk & Zawilski (2021), Proc. R. Soc. A 477:",
        "//   20200776, https://doi.org/10.1098/rspa.2020.0776, updating",
        "//   Stephenson, Morrison & Hohenkerk (2016), Proc. R. Soc. A 472: 20160404,",
        "//   https://doi.org/10.1098/rspa.2016.0404.",
        "// Licence: CC BY 4.0 (figshare item 13885863).",
        f"//   {URL}",
        f"//     {ZIP_NAME} sha256 {ZIP_SHA256}",
        "// Row: year K_i, K_{i+1}; Delta T = a0 + a1 t + a2 t^2 + a3 t^3 seconds,",
        "// t = (Y - K_i) / (K_{i+1} - K_i).",
        f"// {len(rows)} rows.",
        "constexpr SmhSegment kSmhDeltaT[] = {",
    ]
    for r in rows:
        out.append("    {%.1f, %.1f, %.3f, %.3f, %.3f, %.3f}," % r)
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw-dir", required=True)
    ap.add_argument("--fetch", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.fetch:
        fetch(args.raw_dir)
    text = render(parse(args.raw_dir))
    if args.check:
        with open(OUT) as f:
            stale = f.read() != text
        print(f"{OUT}: {'stale' if stale else 'up to date'}")
        sys.exit(1 if stale else 0)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
