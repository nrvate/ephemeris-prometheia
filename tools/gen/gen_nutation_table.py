#!/usr/bin/env python3
"""Generates src/nutation_table.inc from USNO Circular 179 (Kaplan 2005).

The circular prints the complete IAU 2000A (MHB2000) nutation series -
1365 terms - as a table at its end. This script parses that table from a
pdftotext -layout extraction and emits a constexpr C++ array.

Source PDF:  https://aa.usno.navy.mil/downloads/Circular_179.pdf
  (public-domain USNO publication; fetched once with curl,
   extracted with `pdftotext -layout`)

Expected row layout: 21 numbers = term#, M1..M14, S, Sdot, C0, C, Cdot, S0
(coefficients in arcseconds; planetary terms carry zero rates).

Usage: gen_nutation_table.py CIRC179_LAYOUT_TXT OUT_INC
"""
import sys

def main(argv):
    src, dst = argv[1], argv[2]
    lines = open(src).read().splitlines()
    start = None
    for i, l in enumerate(lines):
        if l.strip() == 'IAU 2000A Nutation Series' and i > 4000:
            start = i
            break
    if start is None:
        sys.exit('header line not found')

    rows = []
    for l in lines[start:]:
        t = l.split()
        if len(t) != 21:
            continue
        try:
            nums = [float(x) for x in t]
        except ValueError:
            continue
        if nums[0] != int(nums[0]):
            continue
        rows.append(nums)
    if len(rows) != 1365:
        sys.exit(f'expected 1365 rows, parsed {len(rows)}')
    for expect, got in enumerate(rows, start=1):
        if got[0] != expect:
            sys.exit(f'row order broken at {expect}: {got[0]}')
    # Structural sanity from the circular's own description.
    for r in rows[:678]:
        if any(r[1 + j] != 0 for j in range(9)):
            sys.exit(f'lunisolar row {r[0]} has planetary multipliers')
    for r in rows[678:]:
        if r[16] != 0 or r[19] != 0:
            sys.exit(f'planetary row {r[0]} has nonzero rates')

    def num(x):
        s = f'{x:.7f}'.rstrip('0').rstrip('.')
        return s if s not in ('-0', '') else '0'

    with open(dst, 'w') as f:
        f.write('// GENERATED by tools/gen/gen_nutation_table.py from USNO Circular 179\n')
        f.write('// (Kaplan 2005, public domain), end-of-circular table: the complete\n')
        f.write('// IAU 2000A / MHB2000 nutation series, 1365 terms. Coefficients in\n')
        f.write('// arcseconds; arguments are integer multipliers of the 14 fundamental\n')
        f.write('// arguments phi[0..13] (phi9 indices: 0..8 planetary longitudes +\n')
        f.write('// precession, 9..13 = l, l-prime, F, D, Omega).\n')
        f.write('// Do not edit by hand; regenerate instead.\n')
        f.write('constexpr NutationTerm kNutationTerms[1365] = {\n')
        for r in rows:
            m = ', '.join(str(int(x)) for x in r[1:15])
            coeffs = ', '.join(num(x) for x in r[15:21])
            f.write(f'    {{{{{m}}}, {{{coeffs}}}}},\n')
        f.write('};\n')
    print(f'wrote {dst}: 1365 terms')

if __name__ == '__main__':
    main(sys.argv)
