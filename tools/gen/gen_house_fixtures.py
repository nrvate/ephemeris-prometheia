"""Generate tests/house_fixtures.inc from the Swiss Ephemeris swetest CLI.

Output-only oracle (docs/DESIGN.md, Cleanroom policy): swetest -house is run
as a black box and its printed cusps and angles recorded, with its own ARMC
and delta T, so the test checks the house geometry apart from the sidereal
time. swetest's ARMC departs from the IAU 2006/2000A sidereal time (ERFA
gst06a, which ours matches) by up to 1.8" over 1600-2200 (docs/HOUSES.md).

Rows swetest answers with a convention the definitions do not share are left
out and named in docs/HOUSES.md:
- Placidus and Koch inside a polar circle: swetest substitutes Porphyry
  ("failed, Porphyry calculated instead"); ours refuses.
- Topocentric inside a polar circle: swetest reorders cusps there (the IC
  as cusp 10 with the quadrants mirrored when the MC culminates below the
  horizon, and single opposite pairs flipped at other hours), where ours
  keeps each cusp the eastern point of its pole's horizon.
In the polar rows kept, swetest reports cusp 10 as the MC for Regiomontanus
and Campanus; the MC column there is marked and not compared.

A second, independent table: the IAU 2006/2000A Greenwich apparent sidereal
time from ERFA's gst06a (pyerfa, tools/requirements-oracle.txt) at the same
epochs, which the engine's ARMC is held to.

Usage:
  .venv-oracle/bin/python tools/gen/gen_house_fixtures.py [--swetest PATH] > tests/house_fixtures.inc
"""
import argparse
import math
import re
import subprocess
import sys

import erfa

JD_UT = [2305447.3, 2378496.71, 2415020.13, 2440587.9, 2451545.0, 2461300.42, 2488069.66,
         2524593.2]  # 1600 .. 2200
LATS = [-66.0, -51.5, -33.9, -12.0, 0.0, 0.3, 19.4, 40.7, 55.75, 66.0]
LONS = [-122.4, 8.55, 139.7]
POLAR_LATS = [67.0, 70.0, 80.0, -70.0]
POLAR_HOURS = [0, 4, 8, 12, 16, 20]
SYSTEMS = "PKORCAWBMXT"


def swetest(args, jd, lon, lat, h):
    out = subprocess.run([args.swetest, "-bj%.10g" % jd, "-ut", "-p", "-house%g,%g,%s" % (lon, lat, h),
                          "-fl", "-head", "-emos"], capture_output=True, text=True, check=True).stdout
    failed = any(line.lower().startswith("error") for line in out.splitlines())
    values = [float(v) for line in out.splitlines() if not line.lower().startswith("error")
              for v in line.split()][:17]
    if len(values) != 17:
        sys.exit("swetest: unexpected output: " + out)
    return failed, values


def delta_t(args, jd):
    out = subprocess.run([args.swetest, "-bj%.10g" % jd, "-ut", "-p0", "-emos"], capture_output=True,
                         text=True, check=True).stdout
    return float(re.search(r"delta t:\s*(-?[\d.]+) sec", out).group(1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--swetest", default="/shares/swisseph/swetest")
    args = ap.parse_args()
    rows = []
    for i, jd in enumerate(JD_UT):
        dt = delta_t(args, jd)
        for lat in LATS:
            lon = LONS[(i + LATS.index(lat)) % len(LONS)]
            for h in SYSTEMS:
                failed, v = swetest(args, jd, lon, lat, h)
                if failed:
                    sys.exit("swetest refused %s at %g, %g" % (h, jd, lat))
                rows.append((jd, dt, lon, lat, h, 1, v))
    for lat in POLAR_LATS:
        for hour in POLAR_HOURS:
            jd = 2451545.0 + hour / 24.0
            dt = delta_t(args, jd)
            _, porphyry = swetest(args, jd, 0.0, lat, "O")
            for h in SYSTEMS:
                failed, v = swetest(args, jd, 0.0, lat, h)
                if h in "PK":
                    continue  # refused by ours; tested separately
                mc_swapped = abs(((v[13] - porphyry[13]) + 180.0) % 360.0 - 180.0) > 90.0
                if h == "T":
                    continue  # swetest's polar reordering, not the definition
                rows.append((jd, dt, 0.0, lat, h, 0 if mc_swapped else 1, v))
    print("// Generated by tools/gen/gen_house_fixtures.py -- do not edit.")
    print("// swetest -house output (cusps 1-12, Asc, MC, ARMC, Vertex, equatorial Asc),")
    print("// with its delta T (s). mc_compared = 0 where swetest reports cusp 10 as the MC.")
    print("struct HouseFixture {")
    print("    double jd_ut, delta_t_s, lon_deg, lat_deg;")
    print("    char system;")
    print("    int mc_compared;")
    print("    double v[17];")
    print("};")
    print("constexpr HouseFixture kHouseFixtures[] = {")
    for jd, dt, lon, lat, h, mc, v in rows:
        print("    {%.10g, %.6f, %g, %g, '%s', %d, {%s}}," % (
            jd, dt, lon, lat, h, mc, ", ".join("%.7f" % x for x in v)))
    print("};")
    print("// ERFA gst06a: Greenwich apparent sidereal time (deg) at UT1 = jd_ut, TT = UT1 + delta_t_s.")
    print("struct GastFixture {")
    print("    double jd_ut, delta_t_s, gast_deg;")
    print("};")
    print("constexpr GastFixture kGastFixtures[] = {")
    for jd in JD_UT:
        dt = delta_t(args, jd)
        g = math.degrees(erfa.gst06a(jd, 0.0, jd, dt / 86400.0)) % 360.0
        print("    {%.10g, %.6f, %.10f}," % (jd, dt, g))
    print("};")


if __name__ == "__main__":
    main()
