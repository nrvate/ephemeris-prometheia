"""Generate tests/zodiac_fixtures.inc: the ayanamshas of the zodiacs defined
at the instant, computed independently with ERFA (docs/FRAMES.md, "Zodiacs
defined at the instant").

ERFA (the IAU SOFA algorithms, pip install pyerfa) is an output oracle only,
and every route here differs from the engine's:
- a star: pmsafe (rigorous space motion) from its catalog epoch to the date,
  where the engine moves it linearly;
- Sgr A*: its apparent motion applied in galactic coordinates through ERFA's
  icrs2g/g2icrs, where the engine turns it into RA/Dec proper motion;
- the IAU 1958 galactic pole: ERFA's g2icrs (the Hipparcos catalogue's
  transfer of the pole to the ICRS), where the engine takes Liu et al.'s
  eq. 19. The modern pole has one source only (Liu et al.'s eq. 22);
- the ecliptic: ecm06 (ICRS to the mean ecliptic and equinox of date,
  IAU 2006) with the equinox moved by nut06a's dpsi, where the engine
  composes its own precession and nutation.
The anchor's longitude on the true ecliptic of date less the longitude its
zodiac gives it is the true ayanamsha. Star values come from
src/star_catalog.inc, so the fixtures follow the generated catalog.

Usage: gen_zodiac_fixtures.py [--check]    (needs pyerfa)
"""
import math
import os
import sys

import erfa

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_star_fixtures import load_catalog  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "tests", "zodiac_fixtures.inc")

EPOCHS_TT = [2415020.5, 2433282.5, 2451545.0, 2461300.5, 2488069.5]  # 1900 .. 2100
MULA = 246.0 + 40.0 / 60.0
GIL_BRAND = 210.0 + 90.0 * (3.0 - math.sqrt(5.0)) / 2.0  # 90° / phi^2 from 0° Sco

# Published definitions (Swiss Ephemeris general documentation, 2.8.7-2.8.9
# and 2.8.12 items 4-5): (mode, anchor, anchor data, the anchor's longitude).
MODES = [
    (17, "gc", None, 240.0),
    (27, "star", "HR 5056", 180.0),
    (28, "star", "HR 361", 359.0 + 50.0 / 60.0),
    (29, "star", "HR 3461", 106.0),
    (30, "gc", None, GIL_BRAND),
    (31, "node", "iau1958", 240.0),
    (32, "node", "modern", 240.0),
    (33, "node", "modern", MULA),
    (35, "star", "HR 6527", 240.0),
    (36, "gc-polar", None, MULA),
    (40, "gc", None, 270.0),
]

# Sgr A*: SIMBAD ICRS (epoch J2000.0); Reid & Brunthaler 2020, mas/yr.
SGRA_RA, SGRA_DEC = 266.41681662499997, -29.00782497222222
SGRA_MUL, SGRA_MUB = -6.411, -0.219
# Liu, Zhu & Zhang 2011, eq. 22 (ICRS).
POLE_MODERN = (192.902979992083, 27.103109214444)


def star_icrs(rec, jd):
    ra, dec = math.radians(rec["ra"]), math.radians(rec["dec"])
    mas = math.radians(1.0 / 3.6e6)
    pmr = rec["pmra"] * mas / math.cos(dec)
    pmd = rec["pmdec"] * mas
    px = max(rec["plx"], 0.0) / 1000.0
    rv = rec["rv"] if rec["plx"] > 0 else 0.0
    ep1a, ep1b = erfa.epj2jd(rec["epoch"])
    out = erfa.pmsafe(ra, dec, pmr, pmd, px, rv, ep1a, ep1b, jd, 0.0)
    return erfa.s2c(out[0], out[1])


def gc_icrs(jd):
    l0, b0 = erfa.icrs2g(math.radians(SGRA_RA), math.radians(SGRA_DEC))
    years = (jd - 2451545.0) / 365.25
    mas = math.radians(1.0 / 3.6e6)
    l1 = l0 + SGRA_MUL * mas * years / math.cos(b0)
    b1 = b0 + SGRA_MUB * mas * years
    ra, dec = erfa.g2icrs(l1, b1)
    return erfa.s2c(ra, dec)


def pole_icrs(which):
    if which == "iau1958":
        ra, dec = erfa.g2icrs(0.0, math.pi / 2.0)
    else:
        ra, dec = math.radians(POLE_MODERN[0]), math.radians(POLE_MODERN[1])
    return erfa.s2c(ra, dec)


def mean_ecliptic_lon(jd, v):
    e = erfa.rxp(erfa.ecm06(jd, 0.0), v)
    return math.atan2(e[1], e[0]), e


def true_ayanamsha(mode, jd, catalog):
    _, kind, data, at = mode
    dpsi, deps = erfa.nut06a(jd, 0.0)
    if kind == "star":
        lon, _ = mean_ecliptic_lon(jd, star_icrs(catalog[data], jd))
    elif kind == "gc":
        lon, _ = mean_ecliptic_lon(jd, gc_icrs(jd))
    elif kind == "gc-polar":
        # The hour circle through the mean pole of date (precession only),
        # on the mean equator and ecliptic with the mean equinox.
        q = erfa.rxp(erfa.pmat06(jd, 0.0), gc_icrs(jd))
        ra = math.atan2(q[1], q[0])
        lon = math.atan2(math.sin(ra), math.cos(erfa.obl06(jd, 0.0)) * math.cos(ra))
    else:
        _, p = mean_ecliptic_lon(jd, pole_icrs(data))
        lon = math.atan2(p[0], -p[1])  # n = k x p
        lon %= 2.0 * math.pi
        if lon < math.pi:
            lon += math.pi
    lon_true = math.degrees(lon + dpsi)
    aya = (lon_true - at) % 360.0
    return aya - 360.0 if aya > 180.0 else aya


def main():
    catalog = load_catalog()
    lines = [
        "// Generated by tools/gen/gen_zodiac_fixtures.py -- do not edit.",
        f"// ERFA {erfa.__version__} (IAU SOFA algorithms): the true ayanamsha of each zodiac",
        "// defined at the instant (docs/FRAMES.md). Degrees.",
        "struct ZodiacFixture { int mode; double jd_tt; double true_deg; };",
        "constexpr ZodiacFixture kZodiacFixtures[] = {",
    ]
    for mode in MODES:
        for jd in EPOCHS_TT:
            lines.append(f"    {{{mode[0]}, {jd!r}, {true_ayanamsha(mode, jd, catalog)!r}}},")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        stale = not os.path.exists(OUT) or open(OUT).read() != text
        print(f"{OUT}: {'stale' if stale else 'up to date'}")
        return 1 if stale else 0
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
