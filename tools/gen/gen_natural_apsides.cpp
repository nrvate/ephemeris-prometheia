// prometheia-gen-natural-apsides: the deviation model of the natural lunar
// apogee and perigee (src/natural_apsides.hpp, docs/ORBIT-POINTS.md "The
// natural apsides"), fitted to a JPL DE file. Writes src/natural_apsides.inc.
//
// Every apsis passage of the Moon over the file (100 days in from each end):
// the zeros of the geometric geocentric distance rate, sampled daily and
// bisected to ~1e-9 day. At each one, the deviation of the Moon's longitude
// from the mean apse and the Sun's elongation from it, both geometric and
// geocentric in the mean ecliptic of J2000, the frame the engine interpolates
// in. A least-squares fit of the deviation in kHarmonics harmonics of the
// elongation, per apse; the residual rms and maximum are recorded.
//
// Usage: prometheia-gen-natural-apsides DE_FILE [OUT.inc]   (default stdout)
// Deterministic: the same file gives the same table.
#include <cmath>
#include <cstdio>
#include <string>
#include <vector>

#include <prometheia/de.hpp>
#include <prometheia/engine.hpp>

#include "natural_apsides.hpp"

using namespace prometheia;
namespace na = prometheia::natural_apsides;

namespace {

struct Sample {
    double dev, d; // radians
};

// Solves the normal equations A^T A c = A^T y by Cholesky.
bool solve(std::vector<std::vector<long double>>& m, std::vector<long double>& b,
           double out[na::kTerms]) {
    const int n = na::kTerms;
    for (int j = 0; j < n; ++j) {
        long double s = m[j][j];
        for (int k = 0; k < j; ++k)
            s -= m[j][k] * m[j][k];
        if (!(s > 0))
            return false;
        m[j][j] = std::sqrt(s);
        for (int i = j + 1; i < n; ++i) {
            long double t = m[i][j];
            for (int k = 0; k < j; ++k)
                t -= m[i][k] * m[j][k];
            m[i][j] = t / m[j][j];
        }
    }
    std::vector<long double> y(n);
    for (int i = 0; i < n; ++i) {
        long double t = b[i];
        for (int k = 0; k < i; ++k)
            t -= m[i][k] * y[k];
        y[i] = t / m[i][i];
    }
    for (int i = n - 1; i >= 0; --i) {
        long double t = y[i];
        for (int k = i + 1; k < n; ++k)
            t -= m[k][i] * out[k];
        out[i] = double(t / m[i][i]);
    }
    return true;
}

} // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        std::fprintf(stderr, "usage: prometheia-gen-natural-apsides DE_FILE [OUT.inc]\n");
        return 2;
    }
    auto de = de::DeFile::open(argv[1]);
    auto opened = Engine::open(argv[1]);
    if (!de || !opened) {
        std::fprintf(stderr, "cannot open %s\n", argv[1]);
        return 1;
    }
    Engine& e = opened.value();
    CalcOptions g = CalcOptions::geometric();
    g.frame = Frame::J2000; // ICRF + frame bias, the J2000 ecliptic: the engine's frame
    const auto rate = [&](double t) { return e.calc(body::kMoon, t, g).value().pos.dist_speed; };
    const de::Header& h = de.value().header();
    const double lo = h.start_jed + 100.0, hi = h.end_jed - 100.0;

    std::vector<Sample> samples[2]; // [0] perigee, [1] apogee
    double t = lo, f = rate(t);
    while (t < hi) {
        const double t2 = t + 1.0, f2 = rate(t2);
        if ((f > 0.0) != (f2 > 0.0)) {
            double a = t, b = t2, fa = f;
            for (int i = 0; i < 50; ++i) {
                const double mid = 0.5 * (a + b), fm = rate(mid);
                if ((fm > 0.0) == (fa > 0.0)) {
                    a = mid;
                    fa = fm;
                } else {
                    b = mid;
                }
            }
            const double tp = 0.5 * (a + b);
            const bool apogee = f > 0.0; // the distance rate falls through zero
            const double moon = e.calc(body::kMoon, tp, g).value().pos.lon_deg * M_PI / 180.0;
            const double sun = e.calc(body::kSun, tp, g).value().pos.lon_deg * M_PI / 180.0;
            const double ref = na::mean_apse(tp, apogee);
            samples[apogee].push_back(
                {std::remainder(moon - ref, 2.0 * M_PI), std::remainder(sun - ref, 2.0 * M_PI)});
        }
        t = t2;
        f = f2;
    }

    std::FILE* out = argc > 2 ? std::fopen(argv[2], "w") : stdout;
    if (!out) {
        std::fprintf(stderr, "cannot write %s\n", argv[2]);
        return 1;
    }
    std::fprintf(out, "// Generated by prometheia-gen-natural-apsides from %s -- do not edit.\n",
                 e.source().data());
    std::fprintf(out,
                 "// The deviation of the Moon's actual apsis passages from the mean apse,\n"
                 "// in %d harmonics of the Sun's elongation from it (radians; "
                 "src/natural_apsides.hpp).\n",
                 na::kHarmonics);
    const char* names[2] = {"kPerigeeModel", "kApogeeModel"};
    for (int k = 0; k < 2; ++k) {
        std::vector<std::vector<long double>> m(na::kTerms, std::vector<long double>(na::kTerms));
        std::vector<long double> b(na::kTerms);
        for (const Sample& s : samples[k]) {
            long double row[na::kTerms];
            row[0] = 1;
            for (int h = 1; h <= na::kHarmonics; ++h) {
                row[2 * h - 1] = std::sin(h * s.d);
                row[2 * h] = std::cos(h * s.d);
            }
            for (int i = 0; i < na::kTerms; ++i) {
                b[i] += row[i] * s.dev;
                for (int j = 0; j <= i; ++j)
                    m[i][j] += row[i] * row[j];
            }
        }
        for (int i = 0; i < na::kTerms; ++i)
            for (int j = i + 1; j < na::kTerms; ++j)
                m[i][j] = m[j][i];
        double c[na::kTerms];
        if (!solve(m, b, c)) {
            std::fprintf(stderr, "the fit is singular\n");
            return 1;
        }
        double sum2 = 0.0, worst = 0.0, dev2 = 0.0;
        for (const Sample& s : samples[k]) {
            const double r = s.dev - na::model(c, s.d);
            sum2 += r * r;
            dev2 += s.dev * s.dev;
            worst = std::max(worst, std::fabs(r));
        }
        const double n = double(samples[k].size());
        std::fprintf(out,
                     "// %s: %zu passages; deviation rms %.3f deg; residual rms %.3f deg, max "
                     "%.3f deg\n",
                     k ? "apogee" : "perigee", samples[k].size(), std::sqrt(dev2 / n) * 180 / M_PI,
                     std::sqrt(sum2 / n) * 180 / M_PI, worst * 180 / M_PI);
        std::fprintf(out, "inline constexpr double %s[%d] = {\n", names[k], na::kTerms);
        for (int i = 0; i < na::kTerms; ++i)
            std::fprintf(out, "    %.17g,\n", c[i]);
        std::fprintf(out, "};\n");
    }
    if (out != stdout)
        std::fclose(out);
    return 0;
}
