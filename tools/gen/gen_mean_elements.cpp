// prometheia-gen-mean-elements: the planets' mean orbital elements, fitted
// to a JPL DE file's own osculating elements (docs/ENGINE.md, "Nodes and
// apsides"). Writes src/mean_elements.inc.
//
// For each of the Mercury and Venus centres, the Earth-Moon barycentre and
// the Mars..Pluto system barycentres: the geometric heliocentric state in the
// J2000 ecliptic (ICRF + frame bias, IAU 2006 obliquity) every 4 days over
// the whole file, osculating elements with mu = GM(Sun) + GM(body) from the
// file's header, and a least-squares quadratic in T (Julian centuries TDB
// from J2000) for a and the non-singular elements h = e sin(varpi),
// k = e cos(varpi), p = sin(i) sin(node), q = sin(i) cos(node), which stay
// well defined for the near-zero inclination of the Earth-Moon barycentre
// to the J2000 ecliptic and for small eccentricities. Short-
// period terms average out over the span; what remains is the secular trend,
// which is what a mean element is. The residual rms is recorded per element.
//
// Usage: prometheia-gen-mean-elements DE_FILE [OUT.inc]   (default stdout)
// Deterministic: the same file gives the same table.
#include <cmath>
#include <cstdio>
#include <string>
#include <vector>

#include <prometheia/de.hpp>
#include <prometheia/engine.hpp>
#include <prometheia/kepler.hpp>

using namespace prometheia;

namespace {

constexpr double kJ2000 = 2451545.0;
constexpr double kStepDays = 4.0;

struct Target {
    int id;
    const char* gm_name;
    const char* label;
};

constexpr Target kTargets[] = {
    {199, "GM1", "Mercury"}, {299, "GM2", "Venus"}, {3, "GMB", "Earth-Moon barycentre"},
    {4, "GM4", "Mars"},      {5, "GM5", "Jupiter"}, {6, "GM6", "Saturn"},
    {7, "GM7", "Uranus"},    {8, "GM8", "Neptune"}, {9, "GM9", "Pluto"},
};

// Least squares y ~ c0 + c1 T + c2 T^2; returns the rms residual.
double fit_quadratic(const std::vector<double>& t, const std::vector<double>& y, double c[3]) {
    double n[3][4] = {};
    for (size_t k = 0; k < t.size(); ++k) {
        const double b[3] = {1.0, t[k], t[k] * t[k]};
        for (int i = 0; i < 3; ++i) {
            for (int j = 0; j < 3; ++j)
                n[i][j] += b[i] * b[j];
            n[i][3] += b[i] * y[k];
        }
    }
    // Gaussian elimination with partial pivoting on the 3x3 normal system.
    for (int col = 0; col < 3; ++col) {
        int piv = col;
        for (int r = col + 1; r < 3; ++r)
            if (std::fabs(n[r][col]) > std::fabs(n[piv][col]))
                piv = r;
        for (int j = 0; j < 4; ++j)
            std::swap(n[col][j], n[piv][j]);
        for (int r = col + 1; r < 3; ++r) {
            const double f = n[r][col] / n[col][col];
            for (int j = col; j < 4; ++j)
                n[r][j] -= f * n[col][j];
        }
    }
    for (int i = 2; i >= 0; --i) {
        double s = n[i][3];
        for (int j = i + 1; j < 3; ++j)
            s -= n[i][j] * c[j];
        c[i] = s / n[i][i];
    }
    double ss = 0.0;
    for (size_t k = 0; k < t.size(); ++k) {
        const double r = y[k] - (c[0] + t[k] * (c[1] + t[k] * c[2]));
        ss += r * r;
    }
    return std::sqrt(ss / double(t.size()));
}

} // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        std::fprintf(stderr, "usage: %s DE_FILE [OUT.inc]\n", argv[0]);
        return 2;
    }
    auto de = de::DeFile::open(argv[1]);
    auto engine = Engine::open(argv[1]);
    if (!de || !engine) {
        std::fprintf(stderr, "cannot open %s\n", argv[1]);
        return 1;
    }
    const de::Header& h = de.value().header();
    const auto gms = de.value().constant("GMS");
    if (!gms) {
        std::fprintf(stderr, "%s has no GMS\n", argv[1]);
        return 1;
    }
    FILE* out = argc > 2 ? std::fopen(argv[2], "w") : stdout;
    if (!out) {
        std::fprintf(stderr, "cannot write %s\n", argv[2]);
        return 1;
    }

    CalcOptions o = CalcOptions::geometric();
    o.center = Center::Heliocentric;
    o.frame = Frame::J2000;
    o.sigma = false;
    // Whole samples inside the file, clear of the ends by the rate stencil.
    const double first = std::ceil((h.start_jed + 1.0) / kStepDays) * kStepDays + 0.5;
    const double last = h.end_jed - 1.0;

    std::fprintf(out,
                 "// Generated by prometheia-gen-mean-elements (tools/gen/gen_mean_elements.cpp)\n"
                 "// -- do not edit. Mean elements of the planets: least-squares quadratics\n"
                 "// in T (Julian centuries TDB from J2000) fitted to the osculating\n"
                 "// heliocentric elements of JPL DE%d every %.0f days over JD %.1f .. %.1f,\n"
                 "// referred to the J2000 ecliptic (ICRF + frame bias, IAU 2006 obliquity).\n"
                 "// Rows: a [AU], h = e sin(varpi), k = e cos(varpi), p = sin(i) sin(node),\n"
                 "// q = sin(i) cos(node), each {c0, c1, c2}; then the rms residual of each.\n"
                 "constexpr MeanElementsFit kMeanElements[] = {\n",
                 h.denum, kStepDays, first, last);
    for (const Target& t : kTargets) {
        const auto gm = de.value().constant(t.gm_name);
        if (!gm) {
            std::fprintf(stderr, "%s has no %s\n", argv[1], t.gm_name);
            return 1;
        }
        const double mu = *gms + *gm;
        std::vector<double> T, a, hh, kk, pp, qq;
        for (double jd = first; jd <= last; jd += kStepDays) {
            auto r = engine.value().calc(t.id, time::tt_from_tdb(jd), o);
            if (!r) {
                std::fprintf(stderr, "%s at %.1f: %s\n", t.label, jd, r.error().message.c_str());
                return 1;
            }
            const Position& p = r.value().pos;
            State s;
            s.pos = Vec3{p.xyz_au[0], p.xyz_au[1], p.xyz_au[2]};
            s.vel = Vec3{p.vel_au_day[0], p.vel_au_day[1], p.vel_au_day[2]};
            auto el = state_to_elements(mu, s);
            if (!el) {
                std::fprintf(stderr, "%s at %.1f: %s\n", t.label, jd, el.error().message.c_str());
                return 1;
            }
            const Elements& x = el.value();
            const double varpi = x.node + x.argp;
            T.push_back((jd - kJ2000) / 36525.0);
            a.push_back(x.a);
            hh.push_back(x.e * std::sin(varpi));
            kk.push_back(x.e * std::cos(varpi));
            pp.push_back(std::sin(x.inc) * std::sin(x.node));
            qq.push_back(std::sin(x.inc) * std::cos(x.node));
        }
        double ca[3], ch[3], ck[3], cp[3], cq[3];
        const double ra = fit_quadratic(T, a, ca), rh = fit_quadratic(T, hh, ch),
                     rk = fit_quadratic(T, kk, ck), rp = fit_quadratic(T, pp, cp),
                     rq = fit_quadratic(T, qq, cq);
        std::fprintf(out, "    // %s: %zu samples\n", t.label, T.size());
        std::fprintf(out,
                     "    {%d,\n     {%.17g, %.17g, %.17g},\n     {%.17g, %.17g, %.17g},\n"
                     "     {%.17g, %.17g, %.17g},\n     {%.17g, %.17g, %.17g},\n"
                     "     {%.17g, %.17g, %.17g},\n     {%.3g, %.3g, %.3g, %.3g, %.3g}},\n",
                     t.id, ca[0], ca[1], ca[2], ch[0], ch[1], ch[2], ck[0], ck[1], ck[2], cp[0],
                     cp[1], cp[2], cq[0], cq[1], cq[2], ra, rh, rk, rp, rq);
        // At J2000: the element values and what the residuals mean as angles.
        const double e0 = std::hypot(ch[0], ck[0]), s0 = std::hypot(cp[0], cq[0]);
        std::fprintf(stderr,
                     "%-22s a %.6f e %.6f i %.5f node %.4f varpi %.4f | rms a %.1e AU, "
                     "e.varpi %.1e (%.0f\" of varpi), sin i.node %.1e (%.1f\" of pole)\n",
                     t.label, ca[0], e0, std::asin(s0) * 57.29577951308232,
                     std::atan2(cp[0], cq[0]) * 57.29577951308232,
                     std::atan2(ch[0], ck[0]) * 57.29577951308232, ra, std::hypot(rh, rk),
                     std::hypot(rh, rk) / e0 * 206264.806, std::hypot(rp, rq),
                     std::hypot(rp, rq) * 206264.806);
    }
    std::fprintf(out, "};\n");
    if (out != stdout)
        std::fclose(out);
    return 0;
}
