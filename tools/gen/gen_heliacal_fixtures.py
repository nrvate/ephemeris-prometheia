"""Generate tests/heliacal_fixtures.inc from the Swiss Ephemeris swetest CLI.

Output-only oracle (docs/DESIGN.md, Cleanroom policy): swetest is run as a
black box on JPL's own DE440 binary (-ejpl<file>) and its printed heliacal
events (-hev) are recorded -- the event time, the optimum time and the end
of the visibility window, all UT -- one row per case, with the atmosphere it
was run with beside it (docs/HELIACAL.md, "Validation"). The cases:

- stars at Mediterranean, Mesopotamian, Indian and northern sites, the
  heliacal rising and setting, in the default atmosphere;
- Sirius at Cairo in five atmospheres (humidity, a visual range, a total
  extinction coefficient, a hazy and a clear one): the date moves by days;
- Venus at Berlin, Mercury, Mars, Jupiter and Saturn at Athens, and the
  Moon at Rome: all four events where they exist.

After generating, run clang-format -i on the output (the gate checks it).

Usage:
  tools/gen/gen_heliacal_fixtures.py [--swetest PATH] [--ephe-dir DIR] > tests/heliacal_fixtures.inc
"""
import argparse
import math
import os
import re
import subprocess
import sys

SITES = {
    "Cairo": (31.2, 30.05, 0.0),
    "Athens": (23.73, 37.98, 100.0),
    "Baghdad": (44.4, 33.3, 30.0),
    "Rome": (12.5, 41.9, 20.0),
    "Berlin": (13.4, 52.5, 40.0),
    "Delhi": (77.2, 28.6, 220.0),
}
DEFAULT_ATM = (1013.25, 15.0, 40.0, 0.0)  # pressure, temperature, humidity, visr/ktot

# (our object id, swetest planet argument, site, event, start d.m.y, atmosphere)
CASES = []
for star, site in [("Sirius", "Cairo"), ("Sirius", "Athens"), ("Sirius", "Baghdad"),
                   ("Aldebaran", "Athens"), ("Regulus", "Rome"), ("Spica", "Athens"),
                   ("Arcturus", "Rome"), ("Antares", "Delhi"), ("Fomalhaut", "Cairo"),
                   ("Capella", "Athens"), ("Vega", "Rome"), ("Canopus", "Cairo")]:
    for ev, start in ((1, "1.3.2026" if star == "Fomalhaut" else "1.5.2026"), (2, "1.1.2026")):
        CASES.append((star, "-pf -xf" + star, site, ev, start, DEFAULT_ATM))
for atm in [(1013.25, 15.0, 80.0, 0.0), (1013.25, 15.0, 40.0, 10.0),
            (1013.25, 15.0, 40.0, 0.35), (1013.25, 15.0, 40.0, 60.0),
            (900.0, 25.0, 20.0, 0.0)]:
    CASES.append(("Sirius", "-pf -xfSirius", "Cairo", 1, "1.7.2026", atm))
for ev, start in ((1, "1.10.2026"), (2, "1.4.2028"), (3, "1.1.2027"), (4, "1.1.2027")):
    CASES.append(("Venus", "-p3", "Berlin", ev, start, DEFAULT_ATM))
for name, p in (("Mercury", "-p2"), ("Mars", "-p4"), ("Jupiter", "-p5"), ("Saturn", "-p6")):
    for ev in (1, 2):
        CASES.append((name, p, "Athens", ev, "1.1.2026", DEFAULT_ATM))
for ev in (3, 4):
    CASES.append(("Moon", "-p1", "Rome", ev, "1.1.2026", DEFAULT_ATM))

LINE = re.compile(r"[a-z] *: (\d+)/(\d+)/(\d+) (\d+):(\d+):([\d.]+) UT \(([\d.]+)\), "
                  r"opt (\d+):(\d+):([\d.]+), end (\d+):(\d+):([\d.]+)")


def hms(h, m, s):
    return (int(h) * 3600 + int(m) * 60 + float(s)) / 86400.0


def run(args, case):
    obj, planet, site, ev, start, atm = case
    lon, lat, h = SITES[site]
    cmd = [args.swetest, "-hev%d" % ev] + planet.split() + [
        "-b" + start, "-geopos%g,%g,%g" % (lon, lat, h), "-at%g,%g,%g,%g" % atm, "-n1",
        "-ejpl" + args.ephe_file, "-edir" + os.path.abspath(args.ephe_dir) + ":" + args.star_dir]
    out = subprocess.run(cmd, capture_output=True, text=True).stdout
    m = LINE.search(out)
    if not m:
        sys.stderr.write("no event: %s\n%s\n" % (" ".join(cmd), out))
        return None
    jd = float(m.group(7))
    day0 = math.floor(jd - 0.5) + 0.5
    opt = day0 + hms(*m.group(8, 9, 10))
    end = day0 + hms(*m.group(11, 12, 13))
    while opt < jd - 0.01:
        opt += 1.0
    while end < opt:
        end += 1.0
    return jd, opt, end


def jd_of(dmy):
    d, mo, y = (int(x) for x in dmy.split("."))
    a = (14 - mo) // 12
    yy = y + 4800 - a
    mm = mo + 12 * a - 3
    return d + (153 * mm + 2) // 5 + 365 * yy + yy // 4 - yy // 100 + yy // 400 - 32045 - 0.5


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--swetest", default="/nvm/work/swe-rel/swetest")
    ap.add_argument("--ephe-dir", default="ephe")
    ap.add_argument("--ephe-file", default="linux_p1550p2650.440")
    ap.add_argument("--star-dir", default="/nvm/work/swe-rel/ephe",
                    help="a directory holding the star list swetest reads (sefstars.txt)")
    args = ap.parse_args()
    print("// Generated by tools/gen/gen_heliacal_fixtures.py -- do not edit.")
    print("// swetest -hev on DE440: event, optimum and end of the window, UT Julian dates.")
    print("// object, site name, lon, lat, height, event, start (UT 0h JD),")
    print("// pressure, temperature, humidity, visr/ktot, then the three Julian dates.")
    print("struct HeliacalFixture {")
    print("    const char* object;")
    print("    const char* site;")
    print("    double lon, lat, height;")
    print("    int event;")
    print("    double start_ut;")
    print("    double pressure, temperature, humidity, visr;")
    print("    double event_ut, optimum_ut, end_ut;")
    print("};")
    print("static const HeliacalFixture kHeliacalFixtures[] = {")
    for case in CASES:
        r = run(args, case)
        if r is None:
            continue
        obj, planet, site, ev, start, atm = case
        lon, lat, h = SITES[site]
        print('    {"%s", "%s", %g, %g, %g, %d, %.1f, %g, %g, %g, %g, %.5f, %.5f, %.5f},' %
              (obj, site, lon, lat, h, ev, jd_of(start), atm[0], atm[1], atm[2], atm[3],
               r[0], r[1], r[2]))
    print("};")


if __name__ == "__main__":
    main()
