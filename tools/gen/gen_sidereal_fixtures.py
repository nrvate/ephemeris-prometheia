"""Generate tests/sidereal_fixtures.inc from the Swiss Ephemeris swetest CLI.

Output-only oracle (docs/DESIGN.md, Cleanroom policy): swetest is run as a
black box on JPL's own DE440 binary (-ejpl<file>). Two tables:

- ayanamshas: the -ay<mode> value (the true ayanamsha) at a spread of
  epochs, gating frames::ayanamsa directly;
- positions: apparent sidereal ecliptic longitudes (-sid<mode>), the
  traditional realization ours implements, at four epochs.

Usage:
  tools/gen/gen_sidereal_fixtures.py [--swetest PATH] [--ephe-dir DIR] > tests/sidereal_fixtures.inc
"""
import argparse
import os
import re
import subprocess
import sys

EPOCHS = [2378496.5, 2451545.0, 2461300.25, 2488069.5]  # TT: 1800, J2000, 2026-09, 2100
AYAN_EPOCHS = [2378496.5, 2415020.5, 2433282.5, 2435553.5, 2451545.0,
               2461300.25, 2488069.5, 2501545.0]  # adds 1900 and the two anchors
BODIES = [10, 301, 199, 299, 4, 5, 6, 7, 8, 9]  # swetest -p0123456789 order
MODES = {0: "FaganBradley", 1: "Lahiri"}


def dms(s):
    s = s.strip()
    neg = s.startswith("-")
    m = re.match(r"-?(\d+)°\s*(\d+)'\s*([\d.]+)", s)
    v = int(m.group(1)) + int(m.group(2)) / 60.0 + float(m.group(3)) / 3600.0
    return -v if neg else v


def run(args, extra, fmt, bodies="0123456789"):
    cmd = [args.swetest, "-ejpl" + args.ephe_file, "-edir" + os.path.abspath(args.ephe_dir),
           "-p" + bodies, "-head", "-g|"]
    if fmt:
        cmd.append("-f" + fmt)
    cmd += extra
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    if "error" in out.lower():
        sys.exit("swetest: " + out)
    return [line.split("|") for line in out.strip().splitlines()]


def ayanamsa(args, mode, jd):
    # The ayanamsha line is printed only with the default output format.
    out = run(args, ["-j%.10g" % jd, "-ay%d" % mode], "", "0")
    m = re.search(r"(\d+)°\s*(\d+)'\s*([\d.]+)", out[0][-1])
    return int(m.group(1)) + int(m.group(2)) / 60.0 + float(m.group(3)) / 3600.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--swetest", default="/shares/swisseph/swetest")
    ap.add_argument("--ephe-dir", default="ephe")
    ap.add_argument("--ephe-file", default="linux_p1550p2650.440")
    args = ap.parse_args()

    print("// Generated by tools/gen/gen_sidereal_fixtures.py from swetest on DE440.")
    print("// Do not edit by hand. Degrees.")
    print("struct AyanamsaFixture { int mode; double jd_tt; double deg; };")
    print("const AyanamsaFixture kAyanamsaFixtures[] = {")
    for mode in MODES:
        for jd in AYAN_EPOCHS:
            print("    {%d, %.2f, %.10f}," % (mode, jd, ayanamsa(args, mode, jd)))
    print("};")

    print("struct SiderealFixture { int mode; double jd_tt; int body; double lon, lat; };")
    print("const SiderealFixture kSiderealFixtures[] = {")
    for mode in MODES:
        for jd in EPOCHS:
            rows = run(args, ["-j%.10g" % jd, "-sid%d" % mode], "PLBR")
            for body, r in zip(BODIES, rows):
                print("    {%d, %.2f, %d, %.10f, %.10f}," % (mode, jd, body, dms(r[1]), dms(r[2])))
    print("};")


if __name__ == "__main__":
    main()
