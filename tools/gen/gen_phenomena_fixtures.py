"""Generate tests/phenomena_fixtures.inc from the Swiss Ephemeris swetest CLI.

Output-only oracle (docs/DESIGN.md, Cleanroom policy): swetest is run as a
black box on JPL's own DE440 binary (-ejpl<file>), and its printed phase
angle, illuminated fraction, elongation, apparent diameter and magnitude are
recorded (docs/PHENOMENA.md, "Validation"):

- the Sun, the Moon and the planets at five instants, 1980 to 2100 (1980
  puts Neptune in Mallama & Hilton's 1980-2000 interval);
- Mercury near a 141 deg phase angle and Venus near 171 deg, where their
  phase curves are steepest.

Usage:
  tools/gen/gen_phenomena_fixtures.py [--swetest PATH] [--ephe-dir DIR] > tests/phenomena_fixtures.inc
"""
import argparse
import os
import re
import subprocess
import sys

# TT Julian dates (swetest -j without -ut), so that no delta T enters.
EPOCHS = [2444405.5, 2451544.5, 2461042.0, 2467674.5, 2488069.5]
EXTREMES = [(2461591.0, "2"), (2461337.5, "3")]  # Mercury ~141 deg, Venus ~171 deg
NAIF = {"0": 10, "1": 301, "2": 199, "3": 299, "4": 4, "5": 5, "6": 6, "7": 7, "8": 8}


def dms(s):
    s = s.strip()
    neg = s.startswith("-")
    m = re.match(r"-?(\d+)°\s*(\d+)'\s*([\d.]+)", s)
    v = int(m.group(1)) + int(m.group(2)) / 60.0 + float(m.group(3)) / 3600.0
    return -v if neg else v


def run(args, jd, bodies):
    cmd = [args.swetest, "-ejpl" + args.ephe_file, "-edir" + os.path.abspath(args.ephe_dir),
           "-p" + bodies, "-head", "-g|", "-f+-*/=", "-j%.10g" % jd]
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    if "error" in out.lower():
        sys.exit("swetest: " + out)
    return [line.split("|") for line in out.strip().splitlines()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--swetest", default="/nvm/work/swe-rel/swetest")
    ap.add_argument("--ephe-dir", default="ephe")
    ap.add_argument("--ephe-file", default="linux_p1550p2650.440")
    args = ap.parse_args()
    rows = []
    jobs = [(jd, "012345678") for jd in EPOCHS] + EXTREMES
    for jd, bodies in jobs:
        for b, cols in zip(bodies, run(args, jd, bodies)):
            alpha, frac, elong, diam, mag = (c.strip() for c in cols[:5])
            rows.append((jd, NAIF[b], dms(alpha), float(frac), dms(elong), dms(diam) * 3600.0,
                         float(mag.rstrip("m"))))
    print("// Generated by tools/gen/gen_phenomena_fixtures.py -- do not edit.")
    print("// swetest (output only) on DE440: TT JD, NAIF id, phase angle (deg),")
    print("// illuminated fraction, elongation (deg), diameter (arcsec), V magnitude.")
    print("struct PhenomenaFixture {")
    print("    double jd_tt;")
    print("    long naif;")
    print("    double phase_angle_deg, fraction, elongation_deg, diameter_arcsec, magnitude;")
    print("};")
    print("constexpr PhenomenaFixture kPhenomenaFixtures[] = {")
    for r in rows:
        print("    {%.10g, %d, %.10f, %.9f, %.10f, %.6f, %.3f}," % r)
    print("};")


if __name__ == "__main__":
    main()
