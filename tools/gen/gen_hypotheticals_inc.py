"""Generate src/hypotheticals_shipped.inc from data/hypotheticals.jsonl.

The shipped hypothetical-body element set (docs/HYPOTHETICALS.md) is compiled
into the library as one raw string literal. It used to be generated by CMake
at configure time; it is committed now so that a parent project building the
library from embed/sources.txt with its own makefiles (docs/EMBEDDING.md)
needs no generation step. test_hypotheticals holds the committed file to the
data file byte for byte, so an edit to one without the other fails the gate.

Usage:
  gen_hypotheticals_inc.py            # regenerate src/hypotheticals_shipped.inc
  gen_hypotheticals_inc.py --check    # exit 1 if src/ is stale
"""
import argparse
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(REPO, "data", "hypotheticals.jsonl")
OUT = os.path.join(REPO, "src", "hypotheticals_shipped.inc")
DELIM = "PROMETHEIA_JSONL"
# MSVC refuses a string literal over 16,380 bytes (C2026); one literal is
# kept well inside that rather than split, and refused here if it grows.
MSVC_LITERAL_MAX = 16380


def render(text):
    if ")" + DELIM + '"' in text:
        sys.exit(f"{DATA}: contains the raw-string delimiter {DELIM}")
    if len(text.encode()) > MSVC_LITERAL_MAX:
        sys.exit(f"{DATA}: {len(text.encode())} bytes, over MSVC's {MSVC_LITERAL_MAX}-byte "
                 "literal limit; split the literal before shipping more")
    return ("// SPDX-License-Identifier: GPL-2.0-or-later\n"
            "//\n"
            "// Generated by tools/gen/gen_hypotheticals_inc.py from data/hypotheticals.jsonl;\n"
            "// edit that file and regenerate, not this.\n"
            "constexpr std::string_view kShippedHypotheticals =\n"
            f'    R"{DELIM}({text}){DELIM}";\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if src/ is stale")
    args = ap.parse_args()
    with open(DATA, encoding="utf-8", newline="") as f:
        want = render(f.read())
    if args.check:
        try:
            with open(OUT, encoding="utf-8", newline="") as f:
                have = f.read()
        except FileNotFoundError:
            have = None
        if have != want:
            print(f"{OUT} is stale; run {os.path.relpath(__file__, REPO)}", file=sys.stderr)
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(want)
    return 0


if __name__ == "__main__":
    sys.exit(main())
